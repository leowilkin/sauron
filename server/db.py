"""Database access. Postgres in production (DATABASE_URL), SQLite for local runs and tests.

The SQL is written to run on both: %s placeholders (rewritten to ? for SQLite), TEXT for JSON
and ISO timestamps, INSERT ... ON CONFLICT for upserts.
"""
import json
import os
import sqlite3
import threading

SCHEMA = [
    """CREATE TABLE IF NOT EXISTS users (
        id INTEGER PRIMARY KEY {auto},
        hca_id TEXT UNIQUE NOT NULL,
        slack_id TEXT,
        name TEXT,
        email TEXT,
        username TEXT UNIQUE NOT NULL,
        public INTEGER NOT NULL DEFAULT 1,
        created_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS api_keys (
        id INTEGER PRIMARY KEY {auto},
        user_id INTEGER NOT NULL REFERENCES users(id),
        key_hash TEXT UNIQUE NOT NULL,
        label TEXT,
        created_at TEXT NOT NULL,
        last_used_at TEXT,
        revoked_at TEXT,
        last_n INTEGER NOT NULL DEFAULT 0,
        last_h TEXT
    )""",
    # One row per logged event. Only the allowlisted, counts-only fields are kept in data.
    """CREATE TABLE IF NOT EXISTS events (
        user_id INTEGER NOT NULL REFERENCES users(id),
        key_id INTEGER NOT NULL REFERENCES api_keys(id),
        n INTEGER NOT NULL,
        h TEXT NOT NULL,
        prev TEXT,
        ts TEXT NOT NULL,
        kind TEXT NOT NULL,
        project TEXT,
        data TEXT NOT NULL,
        received_at TEXT NOT NULL,
        PRIMARY KEY (key_id, n)
    )""",
    "CREATE INDEX IF NOT EXISTS events_user_ts ON events (user_id, ts)",
    """CREATE TABLE IF NOT EXISTS labels (
        user_id INTEGER NOT NULL REFERENCES users(id),
        prompt_id TEXT NOT NULL,
        data TEXT NOT NULL,
        PRIMARY KEY (user_id, prompt_id)
    )""",
    """CREATE TABLE IF NOT EXISTS projects (
        user_id INTEGER NOT NULL REFERENCES users(id),
        name TEXT NOT NULL,
        repo_url TEXT,
        PRIMARY KEY (user_id, name)
    )""",
    # Who did what with admin powers: granting, revoking, viewing someone's data.
    """CREATE TABLE IF NOT EXISTS admin_log (
        id INTEGER PRIMARY KEY {auto},
        actor_id INTEGER NOT NULL REFERENCES users(id),
        action TEXT NOT NULL,
        target_id INTEGER REFERENCES users(id),
        at TEXT NOT NULL
    )""",
    # Jev calls made with the shared key, per user per day, for the daily cap.
    """CREATE TABLE IF NOT EXISTS label_usage (
        user_id INTEGER NOT NULL REFERENCES users(id),
        day TEXT NOT NULL,
        n INTEGER NOT NULL DEFAULT 0,
        PRIMARY KEY (user_id, day)
    )""",
    """CREATE TABLE IF NOT EXISTS settings (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
    )""",
    # Every head a device reported, as it arrived. A log rewritten later can't match these.
    """CREATE TABLE IF NOT EXISTS heads (
        id INTEGER PRIMARY KEY {auto},
        key_id INTEGER NOT NULL REFERENCES api_keys(id),
        n INTEGER NOT NULL,
        h TEXT NOT NULL,
        linked INTEGER NOT NULL,
        received_at TEXT NOT NULL
    )""",
]


class DB(object):
    def __init__(self, url=None):
        self.url = url or os.environ.get("DATABASE_URL") or "sqlite:///" + os.path.abspath("ai-tracker.db")
        self.pg = self.url.startswith(("postgres://", "postgresql://"))
        self._local = threading.local()
        self.migrate()

    def conn(self):
        c = getattr(self._local, "c", None)
        if c is None or (self.pg and c.closed):
            if self.pg:
                import psycopg
                c = psycopg.connect(self.url, autocommit=True)
            else:
                c = sqlite3.connect(self.url[len("sqlite:///"):], check_same_thread=False, isolation_level=None)
                c.execute("PRAGMA journal_mode=WAL")
            self._local.c = c
        return c

    def _sql(self, sql):
        return sql if self.pg else sql.replace("%s", "?")

    def execute(self, sql, args=()):
        c = self.conn()
        if self.pg:
            with c.cursor() as cur:
                cur.execute(sql, args)
                return cur.rowcount
        return c.execute(self._sql(sql), args).rowcount

    def query(self, sql, args=()):
        c = self.conn()
        if self.pg:
            with c.cursor() as cur:
                cur.execute(sql, args)
                cols = [d.name for d in cur.description]
                return [dict(zip(cols, row)) for row in cur.fetchall()]
        cur = c.execute(self._sql(sql), args)
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, row)) for row in cur.fetchall()]

    def one(self, sql, args=()):
        rows = self.query(sql, args)
        return rows[0] if rows else None

    def transaction(self):
        return _Tx(self)

    def migrate(self):
        auto = "GENERATED BY DEFAULT AS IDENTITY" if self.pg else "AUTOINCREMENT"
        for stmt in SCHEMA:
            s = stmt.format(auto=auto)
            if self.pg:
                s = s.replace("INTEGER PRIMARY KEY GENERATED", "BIGINT PRIMARY KEY GENERATED")
            self.execute(s)
        # Columns added after the first release. ADD COLUMN IF NOT EXISTS isn't in SQLite, so check first.
        for table, col, decl in (("users", "is_admin", "INTEGER NOT NULL DEFAULT 0"),):
            if not self.has_column(table, col):
                self.execute("ALTER TABLE %s ADD COLUMN %s %s" % (table, col, decl))

    def has_column(self, table, col):
        if self.pg:
            return bool(self.one("SELECT 1 AS x FROM information_schema.columns WHERE table_name = %s AND column_name = %s",
                                 (table, col)))
        return any(r["name"] == col for r in self.query("PRAGMA table_info(%s)" % table))


class _Tx(object):
    def __init__(self, db):
        self.db = db

    def __enter__(self):
        self.db.execute("BEGIN")
        return self.db

    def __exit__(self, exc_type, *a):
        self.db.execute("ROLLBACK" if exc_type else "COMMIT")
        return False


def dumps(d):
    return json.dumps(d, separators=(",", ":"), sort_keys=True)
